function toAppRelativePath(appRoot: string, targetPath: string): string {
  const relativePath = path.relative(appRoot, targetPath);
  return normalizePath(relativePath || ".");
}

async function ensureGeneratedDirectories(
  appRoot: string,
  outDir: string,
  options: { debug: boolean } = { debug: false },
): Promise<GeneratedDirectoryBootstrapResult> {
  const created: string[] = [];
  const missingBeforeCreation: string[] = [];
  const generatedDirs = generatedDirectoryPaths(appRoot, outDir);
  const topLevelDirs = new Set(generatedRootPaths(appRoot, outDir).map((entry) => path.resolve(entry)));

  for (const dir of generatedDirs) {
    const absoluteDir = path.resolve(dir);
    const alreadyExists = await exists(absoluteDir);
    if (!alreadyExists) {
      const displayPath = toAppRelativePath(appRoot, absoluteDir);
      missingBeforeCreation.push(displayPath);
      created.push(displayPath);
      if (options.debug && topLevelDirs.has(absoluteDir)) {
        console.log(`[resux] Created generated directory: ${displayPath}`);
      }
    }
    await mkdir(absoluteDir, { recursive: true });
  }

  return { created, missingBeforeCreation };
}

async function ensureGeneratedPlaceholders(
  appRoot: string,
  outDir: string,
): Promise<{ created: string[] }> {
  const created: string[] = [];
  const placeholders = generatedPlaceholderFiles(appRoot, outDir);

  for (const placeholder of placeholders) {
    if (await exists(placeholder.file)) {
      continue;
    }
    await mkdir(path.dirname(placeholder.file), { recursive: true });
    await writeFile(placeholder.file, placeholder.contents, "utf8");
    created.push(toAppRelativePath(appRoot, placeholder.file));
  }

  return { created };
}

function missingGitignoreEntries(source: string): string[] {
  const lines = source
    .split(/\r?\n/g)
    .map((entry) => entry.trim())
    .filter((entry) => entry.length > 0 && !entry.startsWith("#"));
  const existing = new Set(lines);
  return REQUIRED_GITIGNORE_ENTRIES.filter((entry) => !existing.has(entry));
}

async function checkProject(appRoot: string, outDir: string, options: ResuxCheckOptions = {}): Promise<ResuxCheckReport> {
  const errors: string[] = [];
  const warnings: string[] = [];
  const details: Record<string, unknown> = {};
  const safeFilesResult = await ensureSafeProjectFiles(appRoot, { fix: options.fix === true });
  if (safeFilesResult.created.length > 0) {
    details.createdSafeFiles = safeFilesResult.created;
  }
  if (safeFilesResult.updated.length > 0) {
    details.updatedSafeFiles = safeFilesResult.updated;
  }
  for (const missing of safeFilesResult.missing) {
    warnings.push(`Missing required safe file: ${missing}. Run "resux check --fix" to scaffold it.`);
  }
  const generatedDirs = generatedDirectoryPaths(appRoot, outDir);
  const missingGenerated: string[] = [];
  for (const directory of generatedDirs) {
    if (!(await exists(directory))) {
      missingGenerated.push(toAppRelativePath(appRoot, directory));
    }
  }
  if (missingGenerated.length > 0) {
    details.missingGeneratedDirs = missingGenerated;
    if (options.fix) {
      for (const directory of missingGenerated) {
        console.log(`[resux check] Missing generated directory: ${directory}`);
      }
      const ensured = await ensureGeneratedDirectories(appRoot, outDir, { debug: false });
      for (const createdDir of ensured.created) {
        console.log(`[resux check] Created: ${createdDir}`);
      }
      details.createdGeneratedDirs = ensured.created;
      const placeholderResult = await ensureGeneratedPlaceholders(appRoot, outDir);
      if (placeholderResult.created.length > 0) {
        details.createdGeneratedPlaceholders = placeholderResult.created;
      }
      await ensureNitroBuildFiles(appRoot);
    } else {
      for (const directory of missingGenerated) {
        warnings.push(`Missing generated directory: ${directory}. Run "resux check --fix" or "resux prepare".`);
      }
    }
  } else if (options.fix) {
    const placeholderResult = await ensureGeneratedPlaceholders(appRoot, outDir);
    if (placeholderResult.created.length > 0) {
      details.createdGeneratedPlaceholders = placeholderResult.created;
    }
    await ensureNitroBuildFiles(appRoot);
  }

  const packageFile = path.join(appRoot, "package.json");
  if (!(await exists(packageFile))) {
    errors.push("Missing package.json.");
  }

  const configFile = await firstExistingPath([
    path.join(appRoot, "resux.config.ts"),
    path.join(appRoot, "resux.config.mjs"),
    path.join(appRoot, "resux.config.js"),
  ]);
  if (!configFile) {
    if (options.fix) {
      const generatedConfig = path.join(appRoot, "resux.config.ts");
      await writeFile(generatedConfig, `export default defineResuxConfig({\n  runtimeConfig: {\n    public: {\n      appName: "Resux App"\n    }\n  }\n})\n`, "utf8");
      details.configFile = path.relative(appRoot, generatedConfig);
      warnings.push("Created minimal resux.config.ts.");
    } else {
      errors.push("Missing Resux config file (resux.config.ts/mjs/js).");
    }
  } else {
    details.configFile = path.relative(appRoot, configFile);
  }

  const tsconfigFile = path.join(appRoot, "tsconfig.json");
  if (!(await exists(tsconfigFile))) {
    if (options.fix) {
      await writeFile(
        tsconfigFile,
        `{\n  "compilerOptions": {\n    "target": "ES2022",\n    "module": "ESNext",\n    "moduleResolution": "Bundler",\n    "strict": true,\n    "types": ["node", "resuxjs/globals"]\n  },\n  "include": ["**/*.ts", "**/*.tsx", "**/*.vue", "types/**/*.d.ts", "env.d.ts"]\n}\n`,
        "utf8",
      );
      details.tsconfigFile = path.relative(appRoot, tsconfigFile);
      warnings.push("Created minimal tsconfig.json.");
    } else {
      warnings.push("Missing tsconfig.json. Run \"resux check --fix\" or scaffold it during project creation.");
    }
  } else {
    details.tsconfigFile = path.relative(appRoot, tsconfigFile);
  }

  if (!(await exists(path.join(appRoot, "nitro.config.ts")))) {
    if (options.fix) {
      await ensureNitroBuildFiles(appRoot);
      warnings.push("Created missing nitro.config.ts.");
    } else {
      warnings.push("Missing nitro.config.ts. Run \"resux check --fix\" to scaffold it.");
    }
  }
  if (!(await exists(path.join(appRoot, ".resux-nitro", "handler.ts")))) {
    if (options.fix) {
      await ensureNitroBuildFiles(appRoot);
      warnings.push("Created missing .resux-nitro/handler.ts.");
    } else {
      warnings.push("Missing .resux-nitro/handler.ts. Run \"resux check --fix\" to scaffold it.");
    }
  }

  if (!(await exists(path.join(appRoot, "app.vue")))) {
    warnings.push("Missing app.vue (Resux will still run but starter conventions expect it).");
  }
  if (!(await exists(path.join(appRoot, "pages")))) {
    errors.push("Missing pages/ directory.");
  }
  if (!(await exists(path.join(appRoot, "layouts")))) {
    warnings.push("Missing layouts/ directory.");
  }

  let packageJson: {
    scripts?: Record<string, string>;
    dependencies?: Record<string, string>;
    devDependencies?: Record<string, string>;
  } | null = null;
  if (await exists(packageFile)) {
    try {
      packageJson = JSON.parse(await readFile(packageFile, "utf8")) as {
        scripts?: Record<string, string>;
        dependencies?: Record<string, string>;
        devDependencies?: Record<string, string>;
      };
    } catch (error) {
      errors.push(`Invalid package.json: ${error instanceof Error ? error.message : String(error)}`);
    }
  }

  if (packageJson) {
    const requiredScripts = ["prepare", "dev", "build", "preview", "start", "inspect"];
    const scripts = packageJson.scripts ?? {};
    for (const scriptName of requiredScripts) {
      if (!scripts[scriptName]) {
        warnings.push(`Recommended npm script "${scriptName}" is missing.`);
      }
    }
    const deps = { ...(packageJson.dependencies ?? {}), ...(packageJson.devDependencies ?? {}) };
    if (!deps.resuxjs) {
      errors.push("Dependency \"resuxjs\" is missing from package.json.");
    }
    details.dependencies = Object.keys(deps).sort();
  }

  const builtManifestFile = path.join(outDir, "manifest.json");
  const buildManifestFile = path.join(outDir, "manifest", "build-manifest.json");
  const hasBuiltOutput = await exists(builtManifestFile);
  details.hasBuiltOutput = hasBuiltOutput;
  if (hasBuiltOutput) {
    if (!(await exists(path.join(outDir, "server", "manifest.mjs")))) {
      errors.push("Built output is missing .resux/server/manifest.mjs.");
    }
    if (!(await exists(buildManifestFile))) {
      warnings.push("Built output is missing .resux/manifest/build-manifest.json.");
    }
    if (!(await exists(path.join(outDir, "client", "runtime-client.mjs")))) {
      errors.push("Built output is missing .resux/client/runtime-client.mjs.");
    }
    if (!(await exists(path.join(outDir, "client", "client-enhancements.mjs")))) {
      errors.push("Built output is missing .resux/client/client-enhancements.mjs.");
    }
    if (!(await exists(path.join(appRoot, ".output", "server", "index.mjs")))) {
      warnings.push("Nitro output .output/server/index.mjs is missing. Run \"resux build\".");
    }
    if (!(await exists(path.join(appRoot, ".output", "public", "__resux", "runtime-client.mjs")))) {
      warnings.push("Nitro public asset .output/public/__resux/runtime-client.mjs is missing.");
    }
    if (!(await exists(path.join(appRoot, ".output", "public", "__resux", "client-enhancements.mjs")))) {
      warnings.push("Nitro public asset .output/public/__resux/client-enhancements.mjs is missing.");
    }
  } else {
    warnings.push("No .resux build output found yet. Run \"resux build\" to validate generated artifacts.");
  }

  if (configFile) {
    try {
      const configSource = await readFile(configFile, "utf8");
      if (/packages\s*:\s*\{[\s\S]*clientOnly\s*:/m.test(configSource) && packageJson) {
        const deps = { ...(packageJson.dependencies ?? {}), ...(packageJson.devDependencies ?? {}) };
        const matches = [...configSource.matchAll(/clientOnly\s*:\s*\[([^\]]*)\]/g)];
        for (const match of matches) {
          const values = match[1]
            .split(",")
            .map((entry) => entry.replace(/["'`\s]/g, ""))
            .filter(Boolean);
          for (const pkg of values) {
            if (!deps[pkg]) {
              warnings.push(`packages.clientOnly references "${pkg}" but it is not installed.`);
            }
          }
        }
      }
    } catch {
      // ignore
    }
  }

  return {
    ok: errors.length === 0,
    appRoot,
    outDir,
    errors,
    warnings,
    details,
  };
}

async function ensureSafeProjectFiles(
  appRoot: string,
  options: { fix: boolean },
): Promise<{ created: string[]; updated: string[]; missing: string[] }> {
  const created: string[] = [];
  const updated: string[] = [];
  const missing: string[] = [];
  const pagesDir = path.join(appRoot, "pages");
  const hasPagesDir = await exists(pagesDir);
  const gitignorePath = path.join(appRoot, ".gitignore");
  if (await exists(gitignorePath)) {
    const gitignoreSource = await readFile(gitignorePath, "utf8");
    const entriesToAdd = missingGitignoreEntries(gitignoreSource);
    if (entriesToAdd.length > 0) {
      if (!options.fix) {
        missing.push(`.gitignore entries: ${entriesToAdd.join(", ")}`);
      } else {
        const newline = gitignoreSource.includes("\r\n") ? "\r\n" : "\n";
        const suffix = gitignoreSource.endsWith("\n") || gitignoreSource.length === 0 ? "" : newline;
        const appendedSource = `${gitignoreSource}${suffix}${entriesToAdd.join(newline)}${newline}`;
        await writeFile(gitignorePath, appendedSource, "utf8");
        updated.push(".gitignore");
      }
    }
  }

  const safeFiles: Array<{ path: string; contents: string; condition?: boolean }> = [
    {
      path: ".gitignore",
      contents: `${REQUIRED_GITIGNORE_ENTRIES.join("\n")}\n`,
    },
    {
      path: ".npmrc",
      contents: "engine-strict=true\n",
    },
    {
      path: ".env.example",
      contents: "# Example runtime variables\nAPP_ORIGIN=http://localhost:3000\n",
    },
    {
      path: "types/app.d.ts",
      contents: 'import "resuxjs/globals";\n\nexport {};\n',
    },
    {
      path: "env.d.ts",
      contents: '/// <reference types="resuxjs/globals" />\n',
    },
    {
      path: "assets/css/main.css",
      contents: "body { margin: 0; font-family: \"Segoe UI\", system-ui, sans-serif; }\n",
    },
    {
      path: "public/favicon.svg",
      contents: RESUX_PLACEHOLDER_SVG,
    },
    {
      path: "app.vue",
      contents: `<template>
  <ResuxLayout>
    <ResuxPage />
  </ResuxLayout>
</template>
`,
      condition: hasPagesDir,
    },
  ];

  for (const file of safeFiles) {
    if (file.condition === false) {
      continue;
    }
    const absoluteFile = path.join(appRoot, file.path);
    if (await exists(absoluteFile)) {
      continue;
    }
    if (!options.fix) {
      missing.push(file.path);
      continue;
    }
    await mkdir(path.dirname(absoluteFile), { recursive: true });
    await writeFile(absoluteFile, file.contents, "utf8");
    created.push(file.path);
  }

  return { created, updated, missing };
}

async function generateDeploymentFiles(
  appRoot: string,
  preset: DeployPreset,
  force: boolean,
): Promise<void> {
  await assertDirectory(appRoot);

  const files = [
    {
      relativePath: "DEPLOYMENT.md",
      contents: createDeploymentGuide(preset),
    },
    ...(preset === "nitro"
      ? [
          {
            relativePath: "nitro.config.ts",
            contents: createNitroConfig(),
          },
          {
            relativePath: ".resux-nitro/handler.ts",
            contents: createNitroHandler(),
          },
        ]
      : []),
    ...(preset === "docker"
      ? [
          {
            relativePath: "Dockerfile",
            contents: createDockerfile(),
          },
          {
            relativePath: ".dockerignore",
            contents: createDockerignore(),
          },
        ]
      : []),
  ];
  const written: string[] = [];

  for (const file of files) {
    written.push(
      await writeDeploymentFile(
        appRoot,
        file.relativePath,
        file.contents,
        force,
      ),
    );
  }

  console.log(`Generated Resux ${preset} deployment file(s):`);
  for (const file of written) {
    console.log(`  ${file}`);
  }
}

async function ensureNitroBuildFiles(appRoot: string): Promise<void> {
  const nitroConfigFile = path.join(appRoot, "nitro.config.ts");
  if (!(await exists(nitroConfigFile))) {
    await writeDeploymentFile(
      appRoot,
      "nitro.config.ts",
      createNitroConfig(),
      false,
    );
  } else {
    await upgradeNitroConfigForResux(nitroConfigFile);
  }

  if (!(await exists(path.join(appRoot, ".resux-nitro", "handler.ts")))) {
    await writeDeploymentFile(
      appRoot,
      ".resux-nitro/handler.ts",
      createNitroHandler(),
      false,
    );
  }

  const resolvedBuildDir = normalizeResuxGeneratedPath(await resolveConfiguredBuildDir(appRoot));
  const outDir = path.resolve(appRoot, resolvedBuildDir);
  await updateNitroConfigPrerenderRoutes(appRoot, outDir);
}

async function updateNitroConfigPrerenderRoutes(appRoot: string, outDir: string): Promise<void> {
  const configFile = path.join(appRoot, "nitro.config.ts");
  if (!(await exists(configFile))) {
    return;
  }
  const deployConfig = await loadResuxDeployConfig(appRoot, outDir);
  const isStatic = deployConfig.target === "static";

  let source = await readFile(configFile, "utf8").catch(() => "");
  if (!source) return;

  let prerenderRoutes: string[] = [];
  if (isStatic) {
    const manifestPath = path.join(outDir, "manifest.json");
    const manifest = await readJsonRecord(manifestPath);
    if (manifest && Array.isArray(manifest.routes)) {
      for (const route of manifest.routes) {
        if (!route.params || route.params.length === 0) {
          const rpath = route.path;
          prerenderRoutes.push(rpath);
          if (rpath === "/") {
            prerenderRoutes.push("/__resux/route/payloads/index.json");
          } else {
            prerenderRoutes.push("/__resux/route/payloads" + rpath.replace(/\/$/, "") + ".json");
          }
        }
      }
    }
  }

  let updated = source;
  const prerenderBlockRegex = /prerender\s*:\s*\{[\s\S]*?\}/m;
  const newPrerenderBlock = `prerender: {
    crawlLinks: ${isStatic ? "true" : "false"},
    routes: ${JSON.stringify(prerenderRoutes, null, 2)}
  }`;

  if (prerenderBlockRegex.test(updated)) {
    updated = updated.replace(prerenderBlockRegex, newPrerenderBlock);
  } else {
    updated = updated.replace(
      /export\s+default\s+defineNitroConfig\s*\(\s*\{/,
      `export default defineNitroConfig({\n  ${newPrerenderBlock},`
    );
  }

  if (updated !== source) {
    await writeFile(configFile, updated, "utf8");
    console.log(`Updated nitro.config.ts with ${prerenderRoutes.length} prerender routes for static target.`);
  }
}

async function upgradeNitroConfigForResux(configFile: string): Promise<void> {
  let source: string;
  try {
    source = await readFile(configFile, "utf8");
  } catch {
    return;
  }

  let updated = source;

  const resuxClientAssetBlock =
    /dir:\s*["']\.resux\/client["']\s*,\s*\n\s*baseURL:\s*["']\/__resux["']\s*\n\s*\}/m;
  const match = updated.match(resuxClientAssetBlock);
  if (match && !match[0].includes("fallthrough")) {
    updated = updated.replace(
      resuxClientAssetBlock,
      match[0].replace(/\n\s*\}$/, ",\n      fallthrough: true\n    }"),
    );
  }

  if (
    !updated.includes('"/__resux/image"') &&
    updated.includes('"/api/**":')
  ) {
    updated = updated.replace(
      /(\s+)\"\/api\/\*\*\":\s*\{/,
      `    "/__resux/image": {\n      headers: {\n        "cache-control": "public, max-age=31536000, immutable"\n      }\n    },\n$1"/api/**": {`,
    );
  }

  const cloudflareNodeCompatPattern = /(\bcloudflare\s*:\s*\{[\s\S]*?\bnodeCompat\s*:\s*)(?:true|false)/;
  if (cloudflareNodeCompatPattern.test(updated)) {
    updated = updated.replace(cloudflareNodeCompatPattern, "$1true");
  } else if (/\bcloudflare\s*:\s*\{/.test(updated)) {
    updated = updated.replace(
      /\bcloudflare\s*:\s*\{/,
      (match) => `${match}\n    nodeCompat: true,`,
    );
  } else {
    updated = updated.replace(
      /export\s+default\s+defineNitroConfig\s*\(\s*\{/,
      (match) => `${match}\n  cloudflare: {\n    nodeCompat: true\n  },`,
    );
  }

  if (updated === source) {
    return;
  }

  await writeFile(configFile, updated, "utf8");
  console.log("Updated nitro.config.ts with Resux compatibility defaults.");
}

async function runNitroBuild(
  appRoot: string,
  outDir: string,
  buildOptions: BuildOptions,
): Promise<void> {
  await buildOptions.hooks?.callHook("nitro:init", { appRoot });
  const nitroPackageJson = require.resolve("nitropack/package.json");
  const nitroCli = path.join(
    path.dirname(nitroPackageJson),
    "dist",
    "cli",
    "index.mjs",
  );
  const nitroEnv: NodeJS.ProcessEnv = { ...process.env };
  const deployment = await resolveDeployment(appRoot, outDir, nitroEnv);
  await buildOptions.hooks?.callHook("nitro:config", {
    config: {
      target: deployment.target,
      nitroPreset: deployment.nitroPreset,
    },
  });
  if (deployment.nitroPreset && !nitroEnv.NITRO_PRESET) {
    nitroEnv.NITRO_PRESET = deployment.nitroPreset;
    console.log(
      `Detected deploy target: ${deployment.target} (${deployment.reason})`,
    );
    console.log(`Detected Nitro preset: ${deployment.nitroPreset}`);
  }
  console.log(`Building Nitro output into ${deployment.outputLabel}`);
  await buildOptions.hooks?.callHook("nitro:build:before", {
    appRoot,
    preset: deployment.nitroPreset ?? undefined,
  });

  await new Promise<void>((resolve, reject) => {
    const child = spawn(process.execPath, [nitroCli, "build"], {
      cwd: appRoot,
      stdio: "inherit",
      env: nitroEnv,
    });

    child.on("error", reject);
    child.on("exit", (code) => {
      if (code === 0) {
        resolve();
      } else {
        reject(new Error(`Nitro build exited with code ${code ?? "unknown"}.`));
      }
    });
  });

  await applyDeploymentPostBuild({
    appRoot,
    outDir,
    env: nitroEnv,
    nitroPreset: deployment.nitroPreset,
    target: deployment.target,
  });
  // Resux references app static files under /assets/* (from `@/assets/*` imports
  // and the `css` config), so mirror the app's assets/ dir into the built public
  // dir alongside public/ for production serving.
  const builtPublicDir = path.join(appRoot, ".output", "public");
  const appAssetsDir = path.join(appRoot, "assets");
  if ((await exists(appAssetsDir)) && (await exists(builtPublicDir))) {
    await cp(appAssetsDir, path.join(builtPublicDir, "assets"), {
      recursive: true,
    });
  }
  await buildOptions.hooks?.callHook("nitro:build:public-assets", {
    appRoot,
    publicDir: path.join(appRoot, ".output", "public"),
  });
}

async function assertDirectory(directory: string): Promise<void> {
  const stats = await stat(directory);
  if (!stats.isDirectory()) {
    throw new Error(`${directory} is not a directory.`);
  }
}

async function writeDeploymentFile(
  appRoot: string,
  relativePath: string,
  contents: string,
  force: boolean,
): Promise<string> {
  const file = path.join(appRoot, relativePath);

  if (!force && (await exists(file))) {
    throw new Error(
      `${relativePath} already exists. Re-run with --force to overwrite it.`,
    );
  }

  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, contents, "utf8");
  return relativePath;
}

