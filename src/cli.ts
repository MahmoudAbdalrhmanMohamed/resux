export async function runResuxCli(args: string[]): Promise<void> {
  const command = readCommand(args);
  const commandArgs = command === args[0] ? args.slice(1) : args;

  if (command === "help") {
    printHelp();
    return;
  }

  if (command === "version") {
    console.log(version);
    return;
  }

  if (command === "init" || command === "create") {
    await runCreateResux(commandArgs);
    return;
  }

  if (command === "halal") {
    const subcommand = commandArgs[0];
    const cliOptions = readCliOptions(commandArgs.slice(1), subcommand);
    const appRoot = path.resolve(cliOptions.appRoot);
    const resolvedBuildDir = normalizeResuxGeneratedPath(await resolveConfiguredBuildDir(appRoot));
    const outDir = path.resolve(appRoot, resolvedBuildDir);

    if (subcommand === "check") {
      const ok = await runHalalCheck(appRoot, outDir);
      if (!ok) process.exit(1);
      return;
    }
    if (subcommand === "report") {
      await runHalalReport(appRoot, outDir);
      return;
    }
    if (subcommand === "explain") {
      await runHalalExplain(appRoot);
      return;
    }
    if (subcommand === "submit-review") {
      await runHalalSubmitReview(appRoot, outDir);
      return;
    }
    if (subcommand === "verify-review") {
      const ok = await runHalalVerifyReview(appRoot);
      if (!ok) process.exit(1);
      return;
    }
    console.error(`Unknown halal subcommand "${subcommand}". Allowed: check, report, explain, submit-review, verify-review`);
    process.exit(1);
  }

  const cliOptions = readCliOptions(commandArgs, command);
  const appRoot = path.resolve(cliOptions.appRoot);
  const resolvedBuildDir = normalizeResuxGeneratedPath(await resolveConfiguredBuildDir(appRoot));
  const outDir = path.resolve(appRoot, resolvedBuildDir);
  const buildOptions: BuildOptions = {
    traceBuild: cliOptions.traceBuild === true
  };
  const resuxCore = createResux({ rootDir: appRoot, buildDir: outDir, config: {} });
  buildOptions.hooks = resuxCore.hooks;
  const securityHeaders = cliOptions.securityHeaders ?? command !== "dev";
  const port = readPort(cliOptions.port ?? process.env.PORT, 3000);
  const tailwind = await resolveTailwindPipeline(appRoot);

  if (cliOptions.traceResume) {
    process.env.RESUX_TRACE_RESUME = "1";
  }
  if (cliOptions.traceRoutes) {
    process.env.RESUX_TRACE_ROUTES = "1";
  }
  if (cliOptions.traceBuild) {
    process.env.RESUX_TRACE_BUILD = "1";
  }
  if (cliOptions.https) {
    console.warn("resux --https currently enables HTTPS URLs for routing/open but uses HTTP local server transport.");
  }
  if (cliOptions.debug) {
    console.log(
      `[resux:debug] command=${command} root=${appRoot} outDir=${outDir} port=${port} host=${cliOptions.host ?? "localhost"}`,
    );
  }

  try {
    if (command === "dev" || command === "build" || command === "preview" || command === "start" || command === "prepare") {
      const safeFiles = await ensureSafeProjectFiles(appRoot, { fix: true });
      for (const created of safeFiles.created) {
        console.log(`Created missing safe file: ${created}`);
      }
      for (const updated of safeFiles.updated) {
        console.log(`Updated safe file: ${updated}`);
      }
    }

    if (
      command === "dev"
      || command === "build"
      || command === "preview"
      || command === "start"
      || command === "prepare"
    ) {
      await ensureGeneratedDirectories(appRoot, outDir, { debug: cliOptions.debug === true || command === "dev" });
      await ensureGeneratedPlaceholders(appRoot, outDir);
      await ensureNitroBuildFiles(appRoot);
    }

    if (command === "build") {
      await enforceBuildGuard(appRoot, outDir);
      await runTailwindBuild(appRoot, tailwind, true);
      const result = await runCompilerBuild(appRoot, outDir, {
        ...buildOptions,
        vite: "build",
      });
      await ensureGeneratedDirectories(appRoot, outDir, { debug: cliOptions.debug === true });
      await ensureGeneratedPlaceholders(appRoot, outDir);
      console.log(
        `Built ${result.routes.length} route(s) into ${path.relative(process.cwd(), outDir)}`,
      );
      await ensureNitroBuildFiles(appRoot);
      await runNitroBuild(appRoot, outDir, buildOptions);
    } else if (command === "compile") {
      await enforceBuildGuard(appRoot, outDir);
      await runTailwindBuild(appRoot, tailwind, true);
      const result = await runCompilerBuild(appRoot, outDir, {
        ...buildOptions,
        vite: "build",
      });
      await ensureGeneratedDirectories(appRoot, outDir, { debug: cliOptions.debug === true });
      await ensureGeneratedPlaceholders(appRoot, outDir);
      console.log(
        `Compiled ${result.routes.length} route(s) into ${path.relative(process.cwd(), outDir)}`,
      );
    } else if (command === "deploy") {
      enforceDeploymentGuard(outDir);
      await generateDeploymentFiles(
        appRoot,
        cliOptions.deployPreset,
        cliOptions.force,
      );
    } else if (command === "inspect") {
      await inspectProject(appRoot, outDir, buildOptions, cliOptions.json, cliOptions.inspectTarget);
    } else if (command === "check") {
      const report = await checkProject(appRoot, outDir, { fix: cliOptions.fix, debug: cliOptions.debug });
      if (cliOptions.json) {
        console.log(JSON.stringify(report, null, 2));
      } else {
        console.log(`Resux check: ${report.ok ? "ok" : "issues found"}`);
        console.log(`Root: ${report.appRoot}`);
        if (report.details.createdSafeFiles && Array.isArray(report.details.createdSafeFiles) && report.details.createdSafeFiles.length > 0) {
          console.log("\nCreated safe files");
          for (const created of report.details.createdSafeFiles as string[]) {
            console.log(`  - ${created}`);
          }
        }
        if (report.details.updatedSafeFiles && Array.isArray(report.details.updatedSafeFiles) && report.details.updatedSafeFiles.length > 0) {
          console.log("\nUpdated safe files");
          for (const updated of report.details.updatedSafeFiles as string[]) {
            console.log(`  - ${updated}`);
          }
        }
        if (
          report.details.createdGeneratedDirs
          && Array.isArray(report.details.createdGeneratedDirs)
          && report.details.createdGeneratedDirs.length > 0
        ) {
          console.log("\nCreated generated directories");
          for (const createdDir of report.details.createdGeneratedDirs as string[]) {
            console.log(`  - ${createdDir}`);
          }
        }
        if (
          report.details.createdGeneratedPlaceholders
          && Array.isArray(report.details.createdGeneratedPlaceholders)
          && report.details.createdGeneratedPlaceholders.length > 0
        ) {
          console.log("\nCreated generated placeholders");
          for (const createdPlaceholder of report.details.createdGeneratedPlaceholders as string[]) {
            console.log(`  - ${createdPlaceholder}`);
          }
        }
        if (report.errors.length) {
          console.log("\nErrors");
          for (const error of report.errors) {
            console.log(`  - ${error}`);
          }
        }
        if (report.warnings.length) {
          console.log("\nWarnings");
          for (const warning of report.warnings) {
            console.log(`  - ${warning}`);
          }
        }
      }
      if (!report.ok) {
        process.exitCode = 1;
      }
    } else if (command === "prepare") {
      await runTailwindBuild(appRoot, tailwind, false);
      await runCompilerBuild(appRoot, outDir, { ...buildOptions, vite: "build" });
      await ensureGeneratedDirectories(appRoot, outDir, { debug: cliOptions.debug === true });
      await ensureGeneratedPlaceholders(appRoot, outDir);
      await ensureNitroBuildFiles(appRoot);
      const report = await checkProject(appRoot, outDir, { fix: false, debug: cliOptions.debug });
      if (!report.ok) {
        throw new Error(`resux prepare failed validation. Run "resux check --fix" and retry.`);
      }
      console.log(`Prepared Resux project at ${path.relative(process.cwd(), appRoot) || "."}.`);
    } else if (command === "dev") {
      await enforceDevGuard(appRoot, outDir);
      const policy = await loadProjectPolicy(appRoot);
      const scanned = scanProject(appRoot);
      const report = evaluateRules(scanned, policy);
      if (report.status !== "allowed") {
        devHalalOverlayScript = formatBrowserOverlayScript(report);
      }
      await runTailwindBuild(appRoot, tailwind, false);
      startTailwindWatch(appRoot, tailwind);
      await runCompilerBuild(appRoot, outDir, { ...buildOptions, vite: "dev" });
      await ensureGeneratedDirectories(appRoot, outDir, { debug: cliOptions.debug === true });
      await ensureGeneratedPlaceholders(appRoot, outDir);
      await ensureNitroBuildFiles(appRoot);
      const vite = await startViteDevServer(outDir, buildOptions, cliOptions);
      startDevWatcher(vite, appRoot, outDir, buildOptions);
      await startServer({
        appRoot,
        outDir,
        port,
        host: cliOptions.host,
        open: cliOptions.open === true,
        https: cliOptions.https === true,
        dev: true,
        buildOptions,
        vite,
        securityHeaders,
      });
    } else if (command === "preview" || command === "start") {
      enforcePreviewGuard(outDir);
      if (await previewNeedsBuild(outDir, buildOptions)) {
        await runTailwindBuild(appRoot, tailwind, true);
        await runCompilerBuild(appRoot, outDir, { ...buildOptions, vite: "build" });
        await ensureGeneratedDirectories(appRoot, outDir, { debug: cliOptions.debug === true });
        await ensureGeneratedPlaceholders(appRoot, outDir);
      }
      await startServer({
        appRoot,
        outDir,
        port,
        host: cliOptions.host,
        open: cliOptions.open === true,
        https: cliOptions.https === true,
        dev: false,
        buildOptions,
        securityHeaders,
      });
    } else {
      console.error(
        `Unknown command "${command}". Run resux --help for usage.`,
      );
      process.exitCode = 1;
    }
  } catch (error) {
    console.error(
      error instanceof Error ? (error.stack ?? error.message) : error,
    );
    process.exitCode = 1;
  }
}

async function resolveTailwindPipeline(
  appRoot: string,
): Promise<TailwindPipeline | null> {
  const inputFile = path.join(appRoot, "assets", "css", "tailwind.css");
  if (!(await exists(inputFile))) {
    return null;
  }

  const outputFile = path.join(appRoot, "public", "tailwind.css");
  const configFile = await firstExistingPath([
    path.join(appRoot, "tailwind.config.ts"),
    path.join(appRoot, "tailwind.config.js"),
    path.join(appRoot, "tailwind.config.mjs"),
    path.join(appRoot, "tailwind.config.cjs"),
  ]);
  const cliFile = await resolveTailwindCliFile(appRoot);

  return {
    cliFile,
    inputFile,
    outputFile,
    configFile: configFile ?? undefined,
  };
}

async function resolveTailwindCliFile(appRoot: string): Promise<string> {
  try {
    const appRequire = createRequire(path.join(appRoot, "package.json"));
    const packageJsonPath = appRequire.resolve("tailwindcss/package.json");
    const packageJson = JSON.parse(await readFile(packageJsonPath, "utf8")) as {
      bin?: string | Record<string, string>;
    };
    const binValue =
      typeof packageJson.bin === "string"
        ? packageJson.bin
        : typeof packageJson.bin?.tailwindcss === "string"
          ? packageJson.bin.tailwindcss
          : Object.values(packageJson.bin ?? {})[0];

    if (!binValue) {
      throw new Error("tailwindcss package does not expose a CLI binary.");
    }

    return path.resolve(path.dirname(packageJsonPath), binValue);
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    throw new Error(
      `Detected assets/css/tailwind.css but could not resolve tailwindcss CLI from this app. Install it in app dependencies. ${reason}`,
    );
  }
}

async function runTailwindBuild(
  appRoot: string,
  pipeline: TailwindPipeline | null,
  minify: boolean,
): Promise<void> {
  if (!pipeline) {
    return;
  }

  await mkdir(path.dirname(pipeline.outputFile), { recursive: true });
  const args = [
    pipeline.cliFile,
    "-i",
    pipeline.inputFile,
    "-o",
    pipeline.outputFile,
    ...(pipeline.configFile ? ["--config", pipeline.configFile] : []),
    ...(minify ? ["--minify"] : []),
  ];

  await runChildProcess(process.execPath, args, appRoot);
  console.log(
    `Tailwind build ${minify ? "(minified) " : ""}${path.relative(appRoot, pipeline.inputFile)} -> ${path.relative(appRoot, pipeline.outputFile)}`,
  );
}

function startTailwindWatch(
  appRoot: string,
  pipeline: TailwindPipeline | null,
): ChildProcess | null {
  if (!pipeline) {
    return null;
  }

  const args = [
    pipeline.cliFile,
    "-i",
    pipeline.inputFile,
    "-o",
    pipeline.outputFile,
    ...(pipeline.configFile ? ["--config", pipeline.configFile] : []),
    "--watch",
  ];
  const child = spawn(process.execPath, args, {
    cwd: appRoot,
    stdio: "inherit",
    env: process.env,
    shell: false,
  });

  console.log(
    `Tailwind watch ${path.relative(appRoot, pipeline.inputFile)} -> ${path.relative(appRoot, pipeline.outputFile)}`,
  );

  child.on("exit", (code, signal) => {
    if (signal || code === null || code === 0) {
      return;
    }

    console.error(`Tailwind watch exited with code ${code}.`);
    process.exit(code ?? 1);
  });

  const stop = () => {
    if (!child.killed && child.exitCode === null) {
      child.kill("SIGTERM");
    }
  };

  process.once("exit", stop);
  process.once("SIGINT", stop);
  process.once("SIGTERM", stop);
  process.once("SIGHUP", stop);

  return child;
}

async function runChildProcess(
  command: string,
  args: string[],
  cwd: string,
): Promise<void> {
  await new Promise<void>((resolve, reject) => {
    const child = spawn(command, args, {
      cwd,
      stdio: "inherit",
      env: process.env,
      shell: false,
    });

    child.on("error", reject);
    child.on("exit", (code) => {
      if (code === 0) {
        resolve();
      } else {
        reject(
          new Error(
            `${path.basename(command)} ${args.join(" ")} exited with code ${code ?? "unknown"}.`,
          ),
        );
      }
    });
  });
}

async function firstExistingPath(paths: string[]): Promise<string | null> {
  for (const candidate of paths) {
    if (await exists(candidate)) {
      return candidate;
    }
  }

  return null;
}

function isMainModule(): boolean {
  return process.argv[1]
    ? path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
    : false;
}

function readCommand(args: string[]): string {
  const first = args[0];

  if (first === "init" || first === "create") {
    return first;
  }

  if (args.includes("--help") || args.includes("-h")) {
    return "help";
  }

  if (args.includes("--version") || args.includes("-v")) {
    return "version";
  }

  if (!first || first.startsWith("-")) {
    return "dev";
  }

  if (first === "help" || first === "version") {
    return first;
  }

  return first;
}

function readCliOptions(args: string[], command?: string): CliOptions {
  let appRoot = process.cwd();
  let port: string | undefined;
  let host: string | undefined;
  let open: boolean | undefined;
  let https: boolean | undefined;
  let debug: boolean | undefined;
  let traceResume: boolean | undefined;
  let traceRoutes: boolean | undefined;
  let traceBuild: boolean | undefined;
  let inspectTarget: string | undefined;
  let securityHeaders: boolean | undefined;
  let json = false;
  let deployPreset: DeployPreset = "node";
  let force = false;
  let fix = false;
  const inspectTargets = new Set(["routes", "plugins", "enhancements", "middleware", "imports", "components", "build", "images", "server", "packages", "templates", "bundles", "seo"]);

  for (let index = 0; index < args.length; index++) {
    const arg = args[index];
    if (arg === "--security-headers") {
      securityHeaders = true;
    } else if (arg === "--no-security-headers") {
      securityHeaders = false;
    } else if (arg === "--json") {
      json = true;
    } else if (arg === "--preset") {
      deployPreset = readDeployPreset(
        readRequiredOptionValue(args[++index], arg),
      );
    } else if (arg.startsWith("--preset=")) {
      deployPreset = readDeployPreset(arg.slice("--preset=".length));
    } else if (arg === "--force") {
      force = true;
    } else if (arg === "--fix") {
      fix = true;
    } else if (arg === "--port" || arg === "-p") {
      port = readRequiredOptionValue(args[++index], arg);
    } else if (arg.startsWith("--port=")) {
      port = arg.slice("--port=".length);
    } else if (arg === "--host") {
      host = readRequiredOptionValue(args[++index], arg);
    } else if (arg.startsWith("--host=")) {
      host = arg.slice("--host=".length);
    } else if (arg === "--open") {
      open = true;
    } else if (arg === "--https") {
      https = true;
    } else if (arg === "--debug") {
      debug = true;
    } else if (arg === "--trace-resume") {
      traceResume = true;
    } else if (arg === "--trace-routes") {
      traceRoutes = true;
    } else if (arg === "--trace-build") {
      traceBuild = true;
    } else if (arg.startsWith("-")) {
      throw new Error(`Unknown option "${arg}". Run resux --help for usage.`);
    } else if (!arg.startsWith("-")) {
      if (command === "inspect" && inspectTargets.has(arg)) {
        inspectTarget = arg;
      } else if (appRoot === process.cwd()) {
        appRoot = arg;
      } else if (command === "inspect" && !inspectTarget) {
        inspectTarget = arg;
      } else {
        appRoot = arg;
      }
    }
  }

  return {
    appRoot,
    port,
    host,
    open,
    https,
    debug,
    traceResume,
    traceRoutes,
    traceBuild,
    inspectTarget,
    securityHeaders,
    json,
    deployPreset,
    force,
    fix,
  };
}

function readRequiredOptionValue(
  value: string | undefined,
  option: string,
): string {
  if (!value || value.startsWith("-")) {
    throw new Error(`${option} needs a value.`);
  }
  return value;
}

async function resolveConfiguredBuildDir(appRoot: string): Promise<string> {
  const candidates = [
    path.join(appRoot, "resux.config.ts"),
    path.join(appRoot, "resux.config.mjs"),
    path.join(appRoot, "resux.config.js"),
  ];

  for (const candidate of candidates) {
    if (!(await exists(candidate))) {
      continue;
    }
    try {
      const source = await readFile(candidate, "utf8");
      const match = /buildDir\s*:\s*["'`]([^"'`]+)["'`]/.exec(source);
      if (match?.[1]) {
        return match[1];
      }
    } catch {
      // Fall back to default buildDir.
    }
  }

  return ".resux";
}

function readDeployPreset(value: string): DeployPreset {
  if (value === "node" || value === "docker" || value === "nitro") {
    return value;
  }
  throw new Error(
    `Unknown deploy preset "${value}". Expected "node", "docker", or "nitro".`,
  );
}

async function previewNeedsBuild(
  outDir: string,
  buildOptions: BuildOptions,
): Promise<boolean> {
  if (!(await exists(path.join(outDir, "server", "manifest.mjs")))) {
    return true;
  }

  try {
    const manifest = JSON.parse(
      await readFile(path.join(outDir, "manifest.json"), "utf8"),
    ) as {
      features?: BuildOptions;
      components?: Array<{ id?: string }>;
      plugins?: Array<{ id?: string; mode?: string }>;
      middleware?: Array<{ id?: string; mode?: string }>;
      vueIslands?: Array<{ name?: string }>;
    };
    if (
      manifest.features?.vite !== "build" ||
      manifest.features?.server !== "bundle"
    ) {
      return true;
    }
    const requiredAssets = collectRequiredPreviewAssets(manifest);
    for (const relativePath of requiredAssets) {
      if (!(await exists(path.join(outDir, relativePath)))) {
        if (process.env.RESUX_TRACE_BUILD === "1") {
          console.warn(
            `[resux:trace-build] preview rebuild required, missing asset: ${relativePath}`,
          );
        }
        return true;
      }
    }
    return false;
  } catch {
    return true;
  }
}

function collectRequiredPreviewAssets(manifest: {
  components?: Array<{ id?: string }>;
  plugins?: Array<{ id?: string; mode?: string }>;
  middleware?: Array<{ id?: string; mode?: string }>;
  vueIslands?: Array<{ name?: string }>;
}): string[] {
  const required = new Set<string>(["client/runtime-client.mjs", "client/client-enhancements.mjs"]);
  const componentEntries = Array.isArray(manifest.components)
    ? manifest.components
    : [];
  const pluginEntries = Array.isArray(manifest.plugins) ? manifest.plugins : [];
  const middlewareEntries = Array.isArray(manifest.middleware)
    ? manifest.middleware
    : [];
  const islandEntries = Array.isArray(manifest.vueIslands)
    ? manifest.vueIslands
    : [];

  for (const component of componentEntries) {
    if (!component?.id) {
      continue;
    }
    required.add(`client/handlers/${component.id}.mjs`);
  }
  for (const plugin of pluginEntries) {
    if (!plugin?.id || plugin.mode === "server") {
      continue;
    }
    required.add(`client/plugins/${plugin.id}.mjs`);
  }
  for (const middleware of middlewareEntries) {
    if (!middleware?.id || middleware.mode === "server") {
      continue;
    }
    required.add(`client/middleware/${middleware.id}.mjs`);
  }
  for (const island of islandEntries) {
    if (!island?.name) {
      continue;
    }
    required.add(`client/vue-islands/${island.name}.mjs`);
  }

  return [...required];
}

async function readJsonFile<T>(file: string): Promise<T | null> {
  try {
    return JSON.parse(await readFile(file, "utf8")) as T;
  } catch {
    return null;
  }
}

async function readGeneratedDefaultExport<T>(file: string): Promise<T | null> {
  if (!(await exists(file))) {
    return null;
  }
  try {
    const imported = await import(`${pathToFileURL(file).href}?t=${Date.now()}`);
    return (imported.default ?? null) as T | null;
  } catch {
    return null;
  }
}

async function listRelativeFiles(dir: string, rootDir = dir): Promise<string[]> {
  if (!(await exists(dir))) {
    return [];
  }
  const entries = await readdir(dir, { withFileTypes: true });
  const files: string[] = [];
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...await listRelativeFiles(fullPath, rootDir));
      continue;
    }
    if (!entry.isFile()) {
      continue;
    }
    files.push(normalizePath(path.relative(rootDir, fullPath)));
  }
  return files.sort((left, right) => left.localeCompare(right));
}

function normalizePath(value: string): string {
  return value.split(path.sep).join("/");
}

async function inspectProject(
  appRoot: string,
  outDir: string,
  buildOptions: BuildOptions,
  json = false,
  target?: string,
): Promise<void> {
  if (await previewNeedsBuild(outDir, buildOptions)) {
    await runCompilerBuild(appRoot, outDir, { ...buildOptions, vite: "build" });
  }

  const manifest = JSON.parse(
    await readFile(path.join(outDir, "manifest.json"), "utf8"),
  ) as {
    routes?: Array<{ path: string; file: string }>;
    components?: unknown[];
    layouts?: unknown[];
    plugins?: unknown[];
    clientEnhancements?: unknown[];
    middleware?: unknown[];
    serverMiddleware?: unknown[];
    serverHandlers?: Array<{ path: string; file: string }>;
    routeRules?: Record<string, unknown>;
    features?: BuildOptions;
  };
  const buildManifest = await readJsonFile<Record<string, unknown>>(path.join(outDir, "manifest", "build-manifest.json"));
  const imports = await readGeneratedDefaultExport<Array<Record<string, unknown>>>(path.join(outDir, "imports.mjs"));
  const templateFiles = await listRelativeFiles(path.join(outDir, "templates"));
  const bundleClientFiles = await listRelativeFiles(path.join(outDir, "client"));
  const bundleServerFiles = await listRelativeFiles(path.join(outDir, "server-bundle"));
  const components = manifest.components ?? [];
  const plugins = manifest.plugins ?? [];
  const clientEnhancements = manifest.clientEnhancements ?? [];
  const middleware = manifest.middleware ?? [];
  const serverHandlers = manifest.serverHandlers ?? [];
  const packages = Array.isArray((buildManifest ?? {}).packages)
    ? (buildManifest as { packages: unknown[] }).packages
    : [];
  const routeRules = manifest.routeRules ?? {};
  const seo = await inspectSeoMetadata(appRoot, manifest.routes ?? [], packages);

  const summary = {
    appRoot,
    outDir,
    counts: {
      routes: manifest.routes?.length ?? 0,
      components: manifest.components?.length ?? 0,
      layouts: manifest.layouts?.length ?? 0,
      plugins: manifest.plugins?.length ?? 0,
      clientEnhancements: clientEnhancements.length,
      middleware: manifest.middleware?.length ?? 0,
      serverMiddleware: manifest.serverMiddleware?.length ?? 0,
      serverHandlers: manifest.serverHandlers?.length ?? 0,
      routeRules: Object.keys(routeRules).length,
    },
    features: {
      vite: manifest.features?.vite ?? "build",
      server: manifest.features?.server ?? "modules",
    },
    routes: manifest.routes ?? [],
    serverHandlers,
    routeRules,
    build: buildManifest ?? {},
    imports: imports ?? [],
    components,
    plugins,
    clientEnhancements,
    middleware,
    packages,
    templates: templateFiles,
    bundles: {
      client: bundleClientFiles,
      server: bundleServerFiles,
    },
    images: {
      routeRule: routeRules["/__resux/image"] ?? null,
      transforms: Array.isArray((buildManifest ?? {}).imageTransforms)
        ? (buildManifest as { imageTransforms: unknown[] }).imageTransforms
        : [],
    },
    server: {
      handlers: serverHandlers,
      middleware: manifest.serverMiddleware ?? [],
    },
    seo,
    diagnostics: createInspectDiagnostics(manifest),
  };

  const targetPayload = readInspectTarget(summary, target);

  if (json) {
    console.log(JSON.stringify(targetPayload ?? summary, null, 2));
    return;
  }

  if (targetPayload) {
    console.log(`Resux inspect target: ${target}`);
    console.log(JSON.stringify(targetPayload, null, 2));
    return;
  }

  console.log(`Resux app: ${summary.appRoot}`);
  console.log(`Build dir: ${summary.outDir}`);
  console.log(`Routes: ${summary.counts.routes}`);
  console.log(`Components: ${summary.counts.components}`);
  console.log(`Layouts: ${summary.counts.layouts}`);
  console.log(`Plugins: ${summary.counts.plugins}`);
  console.log(`Client enhancements: ${summary.counts.clientEnhancements}`);
  console.log(`Middleware: ${summary.counts.middleware}`);
  console.log(`Server middleware: ${summary.counts.serverMiddleware}`);
  console.log(`Server handlers: ${summary.counts.serverHandlers}`);
  console.log(`Route rules: ${summary.counts.routeRules}`);
  console.log(
    `Features: vite=${summary.features.vite}, server=${summary.features.server}`,
  );

  if (summary.diagnostics.length) {
    console.log("\nDiagnostics");
    for (const diagnostic of summary.diagnostics) {
      console.log(`  [${diagnostic.level}] ${diagnostic.message}`);
    }
  }

  if (summary.routes.length) {
    console.log("\nRoutes");
    for (const route of summary.routes) {
      console.log(`  ${route.path} -> ${path.relative(appRoot, route.file)}`);
    }
  }

  if (summary.serverHandlers.length) {
    console.log("\nServer handlers");
    for (const handler of summary.serverHandlers) {
      console.log(
        `  ${handler.path} -> ${path.relative(appRoot, handler.file)}`,
      );
    }
  }

  if (Object.keys(routeRules).length) {
    console.log("\nRoute rules");
    for (const [routePath, rule] of Object.entries(routeRules)) {
      console.log(`  ${routePath} ${JSON.stringify(rule)}`);
    }
  }
}

async function inspectSeoMetadata(
  appRoot: string,
  routes: Array<{ path: string; file: string }>,
  packages: unknown[],
): Promise<{
  pages: Array<{
    route: string;
    file: string;
    hasSeoMeta: boolean;
    hasHead: boolean;
    hasH1: boolean;
    hasMain: boolean;
    hasCanonical: boolean;
    hasClientOnlyBlock: boolean;
    warnings: string[];
  }>;
  warnings: string[];
  packageWarnings: string[];
}> {
  const pages: Array<{
    route: string;
    file: string;
    hasSeoMeta: boolean;
    hasHead: boolean;
    hasH1: boolean;
    hasMain: boolean;
    hasCanonical: boolean;
    hasClientOnlyBlock: boolean;
    warnings: string[];
  }> = [];
  const warnings: string[] = [];
  const packageWarnings: string[] = [];

  for (const route of routes) {
    let source = "";
    try {
      source = await readFile(route.file, "utf8");
    } catch {
      continue;
    }
    const hasSeoMeta = /useSeoMeta\s*\(/.test(source);
    const hasHead = /useHead\s*\(/.test(source);
    const hasH1 = /<h1[\s>]/i.test(source);
    const hasMain = /<main[\s>]/i.test(source);
    const hasCanonical = /canonical/i.test(source) || /rel\s*:\s*["']canonical["']/.test(source);
    const hasClientOnlyBlock = /<ClientOnly[\s>]/.test(source) || /<LazyClientOnly[\s>]/.test(source);
    const pageWarnings: string[] = [];
    if (!hasH1) {
      pageWarnings.push("Missing <h1> heading.");
    }
    if (!hasMain) {
      pageWarnings.push("Missing <main> landmark.");
    }
    if (!hasSeoMeta && !hasHead) {
      pageWarnings.push("Missing useSeoMeta()/useHead() metadata.");
    }
    if (hasClientOnlyBlock && /<ClientOnly[\s\S]*<main[\s>]/i.test(source)) {
      pageWarnings.push("ClientOnly appears to wrap a major content block. Prefer SSR-first content plus enhancement.");
    }
    if (route.path.startsWith("/package-tests") && !hasCanonical) {
      pageWarnings.push("Package demo page is missing canonical metadata.");
    }
    if (pageWarnings.length > 0) {
      warnings.push(`${route.path}: ${pageWarnings.join(" ")}`);
    }
    pages.push({
      route: route.path,
      file: path.relative(appRoot, route.file),
      hasSeoMeta,
      hasHead,
      hasH1,
      hasMain,
      hasCanonical,
      hasClientOnlyBlock,
      warnings: pageWarnings,
    });
  }

  for (const entry of packages) {
    if (!entry || typeof entry !== "object" || Array.isArray(entry)) {
      continue;
    }
    const packageName = typeof (entry as { name?: unknown }).name === "string"
      ? (entry as { name: string }).name
      : "unknown";
    const packageEntryWarnings = Array.isArray((entry as { warnings?: unknown }).warnings)
      ? (entry as { warnings: unknown[] }).warnings
      : [];
    for (const warning of packageEntryWarnings) {
      packageWarnings.push(`${packageName}: ${String(warning)}`);
    }
  }

  return {
    pages,
    warnings,
    packageWarnings,
  };
}

function readInspectTarget(
  summary: {
    routes: unknown[];
    plugins: unknown[];
    clientEnhancements: unknown[];
    middleware: unknown[];
    imports: unknown[];
    components: unknown[];
    packages: unknown[];
    templates: unknown[];
    bundles: unknown;
    build: unknown;
    images: unknown;
    server: unknown;
    seo: unknown;
  },
  target?: string,
): unknown | null {
  if (!target) {
    return null;
  }
  if (target === "routes") return summary.routes;
  if (target === "plugins") return summary.plugins;
  if (target === "enhancements") return summary.clientEnhancements;
  if (target === "middleware") return summary.middleware;
  if (target === "imports") return summary.imports;
  if (target === "components") return summary.components;
  if (target === "packages") return summary.packages;
  if (target === "templates") return summary.templates;
  if (target === "bundles") return summary.bundles;
  if (target === "build") return summary.build;
  if (target === "images") return summary.images;
  if (target === "server") return summary.server;
  if (target === "seo") return summary.seo;
  return null;
}

function createInspectDiagnostics(manifest: {
  routes?: Array<{ path: string }>;
  serverHandlers?: Array<{ path: string }>;
  routeRules?: Record<string, unknown>;
}): Array<{ level: "info" | "warning"; message: string }> {
  const diagnostics: Array<{ level: "info" | "warning"; message: string }> = [];

  if (!manifest.routes?.length) {
    diagnostics.push({
      level: "warning",
      message: "No pages were discovered. Add .vue files under pages/.",
    });
  }
  if (!manifest.serverHandlers?.length) {
    diagnostics.push({
      level: "info",
      message:
        "No server handlers were discovered under server/api or server/routes.",
    });
  }
  if (!Object.keys(manifest.routeRules ?? {}).length) {
    diagnostics.push({
      level: "info",
      message: "No route rules are configured.",
    });
  }

  return diagnostics;
}

