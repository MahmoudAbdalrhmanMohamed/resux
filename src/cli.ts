async function handleRequest(
  request: IncomingMessage,
  response: ServerResponse,
  options: {
    appRoot: string;
    outDir: string;
    dev: boolean;
    buildOptions: BuildOptions;
    vite?: ViteDevServer;
    securityHeaders: boolean;
  },
): Promise<void> {
  const requestOrigin = requestOriginFromHeaders(request);
  const requestUrl = safeParseRequestUrl(request.url, requestOrigin);

  try {
    applyDefaultSecurityHeaders(response, options.securityHeaders);
    if (!requestUrl) {
      response.writeHead(404, {
        "content-type": "text/plain; charset=utf-8",
        "cache-control": "no-store",
      });
      response.end("Not found");
      return;
    }

    if (
      options.dev &&
      options.vite &&
      isViteInternalRequest(requestUrl.pathname)
    ) {
      await serveViteMiddleware(request, response, options.vite);
      return;
    }

    if (options.dev && requestUrl.pathname === "/__resux/dev-events") {
      serveDevEvents(request, response);
      return;
    }

    if (requestUrl.pathname === "/__resux/resux-placeholder.svg") {
      serveResuxPlaceholderAsset(response);
      return;
    }

    if (requestUrl.pathname === "/__resux/health") {
      await serveHealthCheck(response, options);
      return;
    }

    if (requestUrl.pathname === "/__resux/route" || requestUrl.pathname.startsWith("/__resux/route/payloads/")) {
      let routePath = "";
      if (requestUrl.pathname === "/__resux/route") {
        routePath = requestUrl.searchParams.get("path") || "/";
      } else {
        const sub = requestUrl.pathname.slice("/__resux/route/payloads/".length);
        if (sub === "index.json") {
          routePath = "/";
        } else {
          routePath = "/" + sub.replace(/\.json$/, "");
        }
      }
      requestUrl.searchParams.set("path", routePath);
      await serveRoutePayload(request, response, requestUrl, options, requestOrigin);
      return;
    }

    if (requestUrl.pathname === "/__resux/image") {
      await serveResuxImage(request, response, requestUrl, requestOrigin);
      return;
    }

    if (requestUrl.pathname === "/__resux/video") {
      await serveResuxVideo(request, response, requestUrl, requestOrigin);
      return;
    }

    if (requestUrl.pathname.startsWith("/_resux/generated/images/")) {
      await serveGeneratedResuxImage(
        request,
        response,
        requestUrl,
        requestOrigin,
        options.appRoot,
      );
      return;
    }

    if (requestUrl.pathname.startsWith("/_resux/generated/videos/")) {
      await serveGeneratedResuxVideo(
        request,
        response,
        requestUrl,
        requestOrigin,
        options.appRoot,
      );
      return;
    }

    if (requestUrl.pathname.startsWith("/__resux/")) {
      if (activeDevBuild) {
        await activeDevBuild;
      }
      if (
        options.dev &&
        options.vite &&
        resolveResuxViteAssetUrl(requestUrl.pathname)
      ) {
        await serveViteResuxAsset(response, options.vite, requestUrl.pathname, options.outDir);
        return;
      }
      await serveResuxAsset(response, options.outDir, requestUrl.pathname);
      return;
    }

    if (options.dev) {
      await ensureDevBuild(
        options.appRoot,
        options.outDir,
        options.buildOptions,
        options.vite,
      );
    }

    const manifest = await importManifest(options.outDir, options.dev);
    const routeRule = matchRouteRule(manifest.routeRules, requestUrl.pathname);
    applyRouteRuleHeaders(response, routeRule);

    if (routeRule?.cors && request.method === "OPTIONS") {
      response.writeHead(204);
      response.end();
      return;
    }

    const middlewareHandled = await runServerMiddleware(
      request,
      response,
      requestUrl,
      manifest,
    );
    if (middlewareHandled) {
      return;
    }

    if (routeRule?.redirect) {
      serveRouteRuleRedirect(response, routeRule.redirect);
      return;
    }

    const serverHandled = await serveServerHandler(
      request,
      response,
      requestUrl,
      manifest,
      routeRule,
    );
    if (serverHandled) {
      return;
    }

    const publicHandled = await servePublicFile(
      response,
      options.appRoot,
      requestUrl.pathname,
    );
    if (publicHandled) {
      return;
    }

    const rendered = await renderRoute(
      requestUrl,
      options,
      manifest,
      requestOrigin,
      request.headers["user-agent"],
    );

    if (!rendered) {
      await serveErrorDocument(
        response,
        options,
        manifest,
        404,
        "Page not found",
      );
      return;
    }

    if ("type" in rendered && rendered.type === "redirect") {
      response.writeHead(rendered.statusCode, { location: rendered.to });
      response.end();
      return;
    }

    if ("type" in rendered && rendered.type === "abort") {
      response.writeHead(rendered.statusCode, {
        "content-type": "text/plain; charset=utf-8",
      });
      response.end(rendered.message);
      return;
    }

    const normalizedRendered = withPrioritizedHeadImagePreloads(rendered);
    let html = promoteDocumentImagePreloads(
      renderDocument(normalizedRendered, "Resux App", {
        devReload: options.dev,
      }),
    );

    if (options.dev && devHalalOverlayScript) {
      html = html.replace("</body>", `<script>${devHalalOverlayScript}</script></body>`);
    }

    response.writeHead(routeRule?.statusCode ?? 200, {
      "content-type": "text/html; charset=utf-8",
    });
    response.end(html);
  } catch (error) {
    console.error("Request failed:", error);
    if (response.writableEnded) {
      return;
    }
    await serveErrorDocument(response, options, undefined, 500, error);
  }
}

function safeParseRequestUrl(rawUrl: string | undefined, requestOrigin: string): URL | null {
  const candidate = typeof rawUrl === "string" ? rawUrl.trim() : "/";
  if (!candidate) {
    return null;
  }
  if (candidate.startsWith("//")) {
    return null;
  }
  try {
    return new URL(candidate, requestOrigin);
  } catch {
    return null;
  }
}

