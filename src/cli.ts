function applyDefaultSecurityHeaders(
  response: ServerResponse,
  enabled: boolean,
): void {
  if (!enabled) {
    return;
  }

  setHeaderIfUnset(response, "x-content-type-options", "nosniff");
  setHeaderIfUnset(
    response,
    "referrer-policy",
    "strict-origin-when-cross-origin",
  );
  setHeaderIfUnset(response, "x-frame-options", "SAMEORIGIN");
  setHeaderIfUnset(response, "cross-origin-opener-policy", "same-origin");
  setHeaderIfUnset(
    response,
    "permissions-policy",
    "camera=(), microphone=(), geolocation=()",
  );
}

function setHeaderIfUnset(
  response: ServerResponse,
  name: string,
  value: string,
): void {
  if (!response.hasHeader(name)) {
    response.setHeader(name, value);
  }
}

async function renderRoute(
  requestUrl: URL,
  options: {
    appRoot: string;
    outDir: string;
    dev: boolean;
    buildOptions: BuildOptions;
    vite?: ViteDevServer;
  },
  loadedManifest?: LoadedManifest,
  requestOrigin?: string,
  userAgent?: string,
): Promise<RenderRouteOutcome> {
  if (options.dev && !loadedManifest) {
    await ensureDevBuild(
      options.appRoot,
      options.outDir,
      options.buildOptions,
      options.vite,
    );
  }

  const manifest =
    loadedManifest ?? (await importManifest(options.outDir, options.dev));
  const matched = manifest.matchRoute(requestUrl.pathname);

  if (!matched) {
    return null;
  }

  const routeContext: RouteContext = {
    path: requestUrl.pathname,
    params: matched.params,
    query: readQuery(requestUrl),
    origin: requestOrigin ?? requestUrl.origin,
    userAgent,
  };
  const middlewareResult = await runRouteMiddleware(
    manifest,
    routeContext,
    matched.route.meta,
  );

  if (middlewareResult) {
    return middlewareResult;
  }

  const rendered = await renderApp({
    app: manifest.app,
    page: matched.route.component,
    pageMeta: matched.route.meta,
    route: routeContext,
    components: manifest.components,
    layouts: manifest.layouts,
    modules: manifest.modules,
    vueIslands: manifest.vueIslands,
    runtimeConfig: manifest.runtimeConfig,
    appHead: manifest.appHead,
    plugins: resolveManifestPlugins(manifest),
  });

  rendered.payload.pageMeta = matched.route.meta ?? {};
  rendered.payload.plugins = manifest.clientPlugins ?? [];
  rendered.payload.middleware = manifest.clientMiddleware ?? [];
  return rendered;
}

function resolveManifestPlugins(manifest: LoadedManifest): ResuxPlugin[] {
  return manifest.resuxPlugins ?? manifest.plugins ?? [];
}

async function runRouteMiddleware(
  manifest: LoadedManifest,
  to: RouteContext,
  pageMeta: PageMeta | undefined,
): Promise<RenderRedirect | RenderAbort | null> {
  const from: RouteContext = { path: "", params: {}, query: {} };
  const names = normalizeMiddlewareNames(pageMeta?.middleware);
  const available = manifest.middleware.filter((entry) => entry.mode !== "client");
  const selected = [
    ...available.filter((entry) => entry.global),
    ...names
      .map((name) =>
        available.find((entry) => entry.name === name),
      )
      .filter((entry): entry is LoadedRouteMiddlewareRecord => Boolean(entry)),
  ];
  const seen = new Set<string>();

  for (const entry of selected) {
    if (seen.has(entry.id)) {
      continue;
    }
    seen.add(entry.id);
    const result = (await entry.handler(to, from)) as RouteMiddlewareResult;
    const normalized = normalizeMiddlewareResult(result);
    if (normalized) {
      return normalized;
    }
  }

  return null;
}

async function runServerMiddleware(
  request: IncomingMessage,
  response: ServerResponse,
  requestUrl: URL,
  manifest: LoadedManifest,
): Promise<boolean> {
  for (const entry of manifest.serverMiddleware ?? []) {
    const result = await entry.handler(
      createServerEvent(request, response, requestUrl, {}),
    );

    if (response.writableEnded) {
      return true;
    }

    if (result === undefined || result === null) {
      continue;
    }

    await sendServerResult(response, result);
    return true;
  }

  return false;
}

function normalizeMiddlewareNames(value: unknown): string[] {
  if (!value) {
    return [];
  }
  return (Array.isArray(value) ? value : [value]).map((name) => String(name));
}

function normalizeMiddlewareResult(
  result: RouteMiddlewareResult,
): RenderRedirect | RenderAbort | null {
  if (result === undefined || result === null) {
    return null;
  }

  if (result === false) {
    return { type: "abort", statusCode: 403, message: "Navigation aborted" };
  }

  if (typeof result === "string") {
    return { type: "redirect", to: result, statusCode: 302 };
  }

  if (
    typeof result === "object"
    && "redirect" in result
    && typeof (result as { redirect?: unknown }).redirect === "string"
  ) {
    return { type: "redirect", to: (result as { redirect: string }).redirect, statusCode: 302 };
  }

  if (
    typeof result === "object"
    && "redirect" in result
    && typeof (result as { redirect?: unknown }).redirect === "object"
    && (result as { redirect?: { to?: unknown } }).redirect
    && typeof (result as { redirect: { to: string; statusCode?: number } }).redirect.to === "string"
  ) {
    const redirect = (result as { redirect: { to: string; statusCode?: number } }).redirect;
    return {
      type: "redirect",
      to: redirect.to,
      statusCode: redirect.statusCode ?? 302,
    };
  }

  if (typeof result === "object" && "type" in result && result.type === "redirect") {
    const redirect = result as { type: "redirect"; to: string; statusCode?: number };
    return {
      type: "redirect",
      to: redirect.to,
      statusCode: redirect.statusCode ?? 302,
    };
  }

  if (typeof result === "object" && "type" in result && result.type === "abort") {
    const abort = result as { type: "abort"; message?: string; statusCode?: number };
    return {
      type: "abort",
      message: abort.message ?? "Navigation aborted",
      statusCode: abort.statusCode ?? 403,
    };
  }

  return null;
}

function isPriorityImagePreloadLinkRecord(link: Record<string, string>): boolean {
  return (
    String(link.rel ?? "").trim().toLowerCase() === "preload"
    && String(link.as ?? "").trim().toLowerCase() === "image"
  );
}

function prioritizeHeadImagePreloads(head: HeadEntry | undefined): void {
  if (!head?.link || !head.link.length) {
    return;
  }

  const priorityLinks = head.link.filter((link) =>
    isPriorityImagePreloadLinkRecord(link)
  );
  if (!priorityLinks.length) {
    return;
  }

  const remainingLinks = head.link.filter((link) =>
    !isPriorityImagePreloadLinkRecord(link)
  );
  head.link = [...priorityLinks, ...remainingLinks];
}

function withPrioritizedHeadImagePreloads(result: RenderResult): RenderResult {
  const clonedHead = result.head
    ? {
      ...result.head,
      link: result.head.link ? [...result.head.link] : result.head.link,
    }
    : result.head;
  prioritizeHeadImagePreloads(clonedHead);
  if (clonedHead === result.head) {
    return result;
  }
  return {
    ...result,
    head: clonedHead,
  };
}

function promoteDocumentImagePreloads(html: string): string {
  const headStart = html.indexOf("<head>");
  const headEnd = html.indexOf("</head>");
  if (headStart === -1 || headEnd === -1 || headEnd <= headStart) {
    return html;
  }

  const headOpenEnd = headStart + "<head>".length;
  const headContent = html.slice(headOpenEnd, headEnd);
  const preloadPattern = /<link\b[^>]*\brel="preload"[^>]*\bas="image"[^>]*>/gi;
  const preloadTags = headContent.match(preloadPattern) ?? [];
  if (!preloadTags.length) {
    return html;
  }

  const headWithoutPreloads = headContent.replace(preloadPattern, "");
  const titleMatch = headWithoutPreloads.match(/<title\b[^>]*>[\s\S]*?<\/title>/i);
  const insertionPoint = titleMatch
    ? headWithoutPreloads.indexOf(titleMatch[0]) + titleMatch[0].length
    : 0;
  const reorderedHeadContent =
    headWithoutPreloads.slice(0, insertionPoint)
    + preloadTags.join("")
    + headWithoutPreloads.slice(insertionPoint);

  return (
    html.slice(0, headOpenEnd)
    + reorderedHeadContent
    + html.slice(headEnd)
  );
}

function matchRouteRule(
  routeRules: Record<string, RouteRule> | undefined,
  pathname: string,
): RouteRule | null {
  if (!routeRules) {
    return null;
  }

  const matched = Object.entries(routeRules)
    .filter(([pattern]) => routeRuleMatches(pattern, pathname))
    .sort(([left], [right]) => routeRuleScore(right) - routeRuleScore(left))[0];

  return matched?.[1] ?? null;
}

function routeRuleMatches(pattern: string, pathname: string): boolean {
  if (pattern === pathname) {
    return true;
  }

  if (pattern.endsWith("/**")) {
    const prefix = pattern.slice(0, -3);
    return pathname === prefix || pathname.startsWith(`${prefix}/`);
  }

  if (!pattern.includes("*")) {
    return false;
  }

  const source = `^${pattern
    .split("**")
    .map((part) => part.split("*").map(escapeRegExp).join("[^/]*"))
    .join(".*")}$`;
  return new RegExp(source).test(pathname);
}

function routeRuleScore(pattern: string): number {
  return (
    pattern.replace(/\*/g, "").length * 10 - (pattern.match(/\*/g)?.length ?? 0)
  );
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function applyRouteRuleHeaders(
  response: ServerResponse,
  rule: RouteRule | null,
): void {
  for (const [name, value] of Object.entries(rule?.headers ?? {})) {
    response.setHeader(name, value);
  }

  const cacheControl = routeRuleCacheControl(rule?.cache);
  if (cacheControl) {
    response.setHeader("cache-control", cacheControl);
  }

  applyCorsRule(response, rule?.cors);
}

function routeRuleCacheControl(
  cache: RouteRule["cache"] | undefined,
): string | null {
  if (cache === undefined) {
    return null;
  }
  if (cache === false) {
    return "no-store";
  }
  if (typeof cache === "string") {
    return cache;
  }

  const parts: string[] = [];
  if (Number.isFinite(cache.maxAge)) {
    parts.push(`public, max-age=${Math.floor(cache.maxAge!)}`);
  }
  if (Number.isFinite(cache.swr)) {
    parts.push(`stale-while-revalidate=${Math.floor(cache.swr!)}`);
  }
  return parts.join(", ") || null;
}

function applyCorsRule(
  response: ServerResponse,
  cors: RouteRule["cors"] | undefined,
): void {
  if (!cors) {
    return;
  }

  const config = cors === true ? {} : cors;
  response.setHeader("access-control-allow-origin", config.origin ?? "*");
  response.setHeader(
    "access-control-allow-methods",
    (
      config.methods ?? [
        "GET",
        "HEAD",
        "POST",
        "PUT",
        "PATCH",
        "DELETE",
        "OPTIONS",
      ]
    ).join(", "),
  );
  response.setHeader(
    "access-control-allow-headers",
    (config.headers ?? ["content-type", "authorization"]).join(", "),
  );
  if (config.credentials) {
    response.setHeader("access-control-allow-credentials", "true");
  }
}

function serveRouteRuleRedirect(
  response: ServerResponse,
  redirect: RouteRule["redirect"],
): void {
  const normalized = normalizeRouteRuleRedirect(redirect);
  response.writeHead(normalized.statusCode, { location: normalized.to });
  response.end();
}

function normalizeRouteRuleRedirect(redirect: RouteRule["redirect"]): {
  to: string;
  statusCode: number;
} {
  if (typeof redirect === "string") {
    return { to: redirect, statusCode: 307 };
  }

  return {
    to: redirect?.to ?? "/",
    statusCode: redirect?.statusCode ?? 307,
  };
}

async function serveServerHandler(
  request: IncomingMessage,
  response: ServerResponse,
  requestUrl: URL,
  manifest: LoadedManifest,
  routeRule: RouteRule | null,
): Promise<boolean> {
  const matched = manifest.matchServerHandler?.(requestUrl.pathname);
  if (!matched) {
    return false;
  }

  const result = await matched.route.handler(
    createServerEvent(request, response, requestUrl, matched.params),
  );

  if (response.writableEnded) {
    return true;
  }

  await sendServerResult(response, result, routeRule?.statusCode ?? 200);
  return true;
}

function createServerEvent(
  request: IncomingMessage,
  response: ServerResponse,
  requestUrl: URL,
  params: Record<string, string>,
) {
  return {
    path: requestUrl.pathname,
    method: request.method ?? "GET",
    query: readQuery(requestUrl),
    params,
    node: {
      req: request,
      res: response,
    },
  };
}

async function sendServerResult(
  response: ServerResponse,
  result: unknown,
  statusCode = 200,
): Promise<void> {
  if (result instanceof Response) {
    const headers: Record<string, string> = {};
    result.headers.forEach((value, key) => {
      headers[key] = value;
    });
    response.writeHead(result.status, headers);
    response.end(Buffer.from(await result.arrayBuffer()));
    return;
  }

  if (result === false) {
    response.writeHead(403, { "content-type": "text/plain; charset=utf-8" });
    response.end("Forbidden");
    return;
  }

  if (isServerRedirectResult(result)) {
    response.writeHead(result.statusCode ?? 302, { location: result.to });
    response.end();
    return;
  }

  if (isServerAbortResult(result)) {
    response.writeHead(result.statusCode ?? 403, {
      "content-type": "text/plain; charset=utf-8",
    });
    response.end(result.message ?? "Request aborted");
    return;
  }

  if (typeof result === "string") {
    response.writeHead(statusCode, {
      "content-type": "text/plain; charset=utf-8",
    });
    response.end(result);
    return;
  }

  response.writeHead(statusCode, {
    "content-type": "application/json; charset=utf-8",
  });
  response.end(JSON.stringify(result ?? null));
}

function isServerRedirectResult(
  value: unknown,
): value is { type: "redirect"; to: string; statusCode?: number } {
  return Boolean(
    value &&
    typeof value === "object" &&
    (value as { type?: unknown }).type === "redirect" &&
    typeof (value as { to?: unknown }).to === "string",
  );
}

function isServerAbortResult(
  value: unknown,
): value is { type: "abort"; message?: string; statusCode?: number } {
  return Boolean(
    value &&
    typeof value === "object" &&
    (value as { type?: unknown }).type === "abort",
  );
}

async function servePublicFile(
  response: ServerResponse,
  appRoot: string,
  pathname: string,
): Promise<boolean> {
  const publicRoot = path.resolve(appRoot, "public");
  const candidates: Array<{ base: string; boundary: string }> = [
    { base: publicRoot, boundary: publicRoot },
  ];
  // Resux compiles `@/assets/*` imports (and the `css` config) to `/assets/*`
  // URLs, so also serve the app's assets/ directory as a static root. The
  // boundary check keeps this scoped to assets/ and blocks path traversal.
  if (pathname === "/assets" || pathname.startsWith("/assets/")) {
    candidates.push({ base: appRoot, boundary: path.resolve(appRoot, "assets") });
  }

  for (const { base, boundary } of candidates) {
    const resolved = path.resolve(base, `.${decodeURIComponent(pathname)}`);
    if (!resolved.startsWith(boundary)) {
      continue;
    }
    if (!(await exists(resolved))) {
      continue;
    }
    const fileStats = await stat(resolved);
    if (!fileStats.isFile()) {
      continue;
    }

    response.writeHead(200, {
      "content-type": mimeType(resolved),
      ...(!response.hasHeader("cache-control")
        ? { "cache-control": "no-store" }
        : {}),
    });
    response.end(await readFile(resolved));
    return true;
  }
  return false;
}

function mimeType(file: string): string {
  const ext = path.extname(file).toLowerCase();
  const types: Record<string, string> = {
    ".css": "text/css; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".html": "text/html; charset=utf-8",
    ".txt": "text/plain; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".webp": "image/webp",
    ".avif": "image/avif",
    ".gif": "image/gif",
    ".mp4": "video/mp4",
    ".webm": "video/webm",
    ".mov": "video/quicktime",
    ".ico": "image/x-icon",
  };
  return types[ext] ?? "application/octet-stream";
}

async function ensureDevBuild(
  appRoot: string,
  outDir: string,
  buildOptions: BuildOptions,
  vite?: ViteDevServer,
): Promise<boolean> {
  const startedAtRevision = devBuildRevision;
  const sourceMtime = latestSourceMtime(appRoot, outDir);
  if (sourceMtime > devLastBuildSourceMtime) {
    devLastBuildSourceMtime = sourceMtime;
    devBuildDirty = true;
  }

  while (devBuildDirty || activeDevBuild) {
    if (!activeDevBuild) {
      devBuildDirty = false;
      activeDevBuild = runCompilerBuild(appRoot, outDir, {
        ...buildOptions,
        vite: "dev",
      })
        .then(() => {
          devBuildRevision++;
          vite?.moduleGraph.invalidateAll();
        })
        .finally(() => {
          activeDevBuild = null;
        });
    }

    await activeDevBuild;
  }

  return devBuildRevision !== startedAtRevision;
}

function serveDevEvents(
  request: IncomingMessage,
  response: ServerResponse,
): void {
  response.writeHead(200, {
    "content-type": "text/event-stream; charset=utf-8",
    "cache-control": "no-store, no-transform",
    connection: "keep-alive",
  });
  response.write("retry: 1000\n\n");
  devReloadClients.add(response);

  request.on("close", () => {
    devReloadClients.delete(response);
  });
}

function notifyDevReloadClients(eventName: "hmr" | "reload" = "hmr"): void {
  devReloadRevision++;
  const payload = JSON.stringify({ revision: devReloadRevision });

  for (const client of [...devReloadClients]) {
    if (client.destroyed || client.writableEnded) {
      devReloadClients.delete(client);
      continue;
    }

    try {
      client.write(`event: ${eventName}\ndata: ${payload}\n\n`);
    } catch {
      devReloadClients.delete(client);
    }
  }
}

async function serveViteResuxAsset(
  response: ServerResponse,
  vite: ViteDevServer,
  pathname: string,
  outDir: string,
): Promise<void> {
  if (pathname === "/__resux/runtime-client.mjs") {
    const source = `export * from "/runtime-client.mjs";\nimport "/runtime-client.mjs";\n`;
    response.writeHead(200, {
      "content-type": "text/javascript; charset=utf-8",
      "cache-control": "no-store",
    });
    response.end(source);
    return;
  }

  if (pathname === "/__resux/client-enhancements.mjs") {
    const manifestFile = path.join(outDir, "vite-client", "client-enhancements.mjs");
    if (!(await exists(manifestFile))) {
      response.writeHead(404);
      response.end("Not found");
      return;
    }
    const source = await readFile(manifestFile, "utf8");
    response.writeHead(200, {
      "content-type": "text/javascript; charset=utf-8",
      "cache-control": "no-store",
    });
    response.end(source);
    return;
  }

  const viteUrl = resolveResuxViteAssetUrl(pathname);

  if (!viteUrl) {
    response.writeHead(404);
    response.end("Not found");
    return;
  }

  const transformed = await vite.transformRequest(viteUrl);

  if (!transformed) {
    response.writeHead(404);
    response.end("Not found");
    return;
  }

  response.writeHead(200, {
    "content-type": "text/javascript; charset=utf-8",
    "cache-control": "no-store",
  });
  response.end(transformed.code);
}

async function serveViteMiddleware(
  request: IncomingMessage,
  response: ServerResponse,
  vite: ViteDevServer,
): Promise<void> {
  await new Promise<void>((resolve, reject) => {
    let settled = false;
    const finish = () => {
      if (!settled) {
        settled = true;
        resolve();
      }
    };

    response.once("finish", finish);
    vite.middlewares(request, response, (error?: unknown) => {
      response.off("finish", finish);

      if (settled) {
        return;
      }

      settled = true;

      if (error) {
        reject(error instanceof Error ? error : new Error(String(error)));
        return;
      }

      if (!response.writableEnded) {
        response.writeHead(404);
        response.end("Not found");
      }

      resolve();
    });
  });
}

async function serveResuxAsset(
  response: ServerResponse,
  outDir: string,
  pathname: string,
): Promise<void> {
  const relative = resolveResuxAssetPath(pathname);

  if (!relative) {
    response.writeHead(404);
    response.end("Not found");
    return;
  }

  const resolved = path.resolve(outDir, relative);
  const allowedRoot = path.resolve(outDir, "client");

  if (!resolved.startsWith(allowedRoot)) {
    response.writeHead(403);
    response.end("Forbidden");
    return;
  }

  if (!(await exists(resolved))) {
    if (process.env.RESUX_TRACE_BUILD === "1") {
      console.warn(
        `[resux:trace-build] asset missing for ${pathname} resolved to ${resolved}`,
      );
    }
    response.writeHead(404);
    response.end("Not found");
    return;
  }

  const fileContents = await readFile(resolved);
  response.writeHead(200, {
    "content-type": mimeType(resolved),
    "cache-control": "no-store",
  });
  response.end(fileContents);
}

