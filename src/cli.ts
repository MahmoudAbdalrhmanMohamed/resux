async function importManifest(outDir: string, dev = false): Promise<LoadedManifest> {
  const file =
    !dev && (await exists(path.join(outDir, "server-bundle", "index.mjs")))
      ? path.join(outDir, "server-bundle", "index.mjs")
      : path.join(outDir, "server", "manifest.mjs");
  const stats = await stat(file);
  return import(`${pathToFileURL(file).href}?t=${stats.mtimeMs}`) as Promise<LoadedManifest>;
}

function readQuery(url: URL): Record<string, string | string[]> {
  const query: Record<string, string | string[]> = {};

  for (const [key, value] of url.searchParams) {
    const existing = query[key];
    if (Array.isArray(existing)) {
      existing.push(value);
    } else if (existing !== undefined) {
      query[key] = [existing, value];
    } else {
      query[key] = value;
    }
  }

  return query;
}

async function exists(file: string): Promise<boolean> {
  try {
    await stat(file);
    return true;
  } catch {
    return false;
  }
}
